//стандартная структура узла, которая была на leetcode
struct ListNode {
	int val; //значение текущего узла
	ListNode* next; //указтель на следующий узел
	ListNode() : val(0), next(nullptr) {} //конструктор по умолчанию
	ListNode(int x) : val(x), next(nullptr) {} //конструктор, создающий узел только со значением
	ListNode(int x, ListNode* next) : val(x), next(next) {} //конструктор, создающий узел со значением и указателем на следующий
};

class Solution {
public:
	ListNode* mergeNodes(ListNode* head) {
		ListNode* resultHead = nullptr; //указатель на начало результирующего списка
		ListNode* resultTail = nullptr; //указатель на конец результирующего списка

		int currentSegmentSum = 0; //переменная для накопления суммы текущего участка между нулями
		ListNode* currentNode = head->next; //начинаем со второго узла, так как первый всегда 0 и не нужен

		//проходим по всему списку
		while (currentNode != nullptr) {
			//если встретили 0, значит текущий участок закончился
			if (currentNode->val == 0) {
				//создаем новый узел со значение накопленной суммы
				ListNode* newNode = new ListNode(currentSegmentSum);

				//если это первый узел результата
				if (resultHead == nullptr) {
					//новый узел становится одновременно начало и концом списка
					resultHead = newNode;
					resultTail = newNode;
				}
				else {
					//иначе добавляем новый узел в конец результирующего списка
					resultTail->next = newNode;
					resultTail = newNode; //сдвигаем хвост на новый последний элемент
				}

				currentSegmentSum = 0; //обнуляем сумму для следующего участка
			}
			else {
				currentSegmentSum += currentNode->val; //если текущий узел не 0, то добавляем его в текущую сумму
			}

			currentNode = currentNode->next; //переходим к след узлу исходного списка
		}

		return resultHead; //возвращаем начало сформированного списка
	}
};

/*
* Суть задачи: дан односвязный список, в котором значения разбиты нулями на отдельные группы.
* Первый и последний узлы списка всегда содержат 0.
* Нужно для каждой группы чисел между двумя соседними нулями посчитать сумму и сформировать новый список
* только из этих сумм, без нулей.
*
* Решение:
* Будем проходить по исходному списку, начиная со второго узла, так как первый узел всегда равен 0
* и в вычислениях не участвует.
* Во время обхода поддерживаем переменную currentSegmentSum, в которой накапливаем сумму текущего участка между нулями.
*
* Если текущий узел не равен 0, просто добавляем его значение к currentSegmentSum.
*
* Если текущий узел равен 0, это означает, что очередной участок закончился.
* В этот момент создаём новый узел, в который записываем накопленную сумму и добавляем этот узел в конец результирующего списка.
* После этого обнуляем currentSegmentSum и продолжаем обход.
*
* Так как результирующий список создаётся отдельно, то нужны два указателя:
* resultHead — указатель на первый узел результата,
* resultTail — указатель на последний узел результата, чтобы удобно добавлять новые элементы в конец.
* Если это первый найденный участок, то новый узел становится и головой, и хвостом результата.
* Иначе просто присоединяем его к resultTail->next и сдвигаем resultTail вперёд.
* В конце возвращаем resultHead — начало нового списка.
*
* Почему решение корректно:
* 1) По условию первый и последний узлы всегда равны 0, значит каждая группа чисел точно ограничена нулями.
* 2) Между двумя нулями нет других разделителей, поэтому можно просто накапливать сумму,
*    пока не встретится очередной 0.
* 3) Каждый раз при встрече 0 мы завершаем ровно одну группу и добавляем в результат
*    ровно одну сумму.
* Таким образом, в новый список попадут суммы всех групп и не попадут сами нули.
*
* Оценка сложности по времени: O(n), так как список проходится один раз.
*/